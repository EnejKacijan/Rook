// Compile only public provenance/credits. Internal evidence, hashes and
// generation records stay in docs/visual-provenance.json, outside the bundle.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'docs/visual-provenance.json'), 'utf8'));
const runtime = manifest.assets.filter(asset => asset.usage === 'runtime_exercise');
const ids = new Set(runtime.map(asset => asset.assetId));
if (ids.size !== runtime.length) throw new Error('Duplicate runtime provenance ID.');
for (const asset of runtime) {
  if (!['rook_ai_generated', 'rook_original', 'licensed_third_party', 'public_domain', 'unknown'].includes(asset.provenanceType)) throw new Error(`Invalid image provenance: ${asset.assetId}`);
  if (asset.attributionRequired && !asset.publicCredit) throw new Error(`Missing required credit: ${asset.assetId}`);
}
const ai = runtime.filter(asset => asset.provenanceType === 'rook_ai_generated').map(asset => asset.assetId).sort();
const other = Object.fromEntries(runtime.filter(asset => asset.provenanceType !== 'rook_ai_generated').map(asset => [asset.assetId, {
  assetId: asset.assetId, provenanceType: asset.provenanceType, attributionRequired: asset.attributionRequired,
  credit: asset.publicCredit || null,
}]));
const disclosure = ai.length === runtime.length ? 'Exercise illustrations were generated for ROOK using AI and reviewed for exercise identification.'
  : ai.length > runtime.length / 2 ? 'Most exercise illustrations were generated for ROOK using AI and reviewed for exercise identification.'
  : ai.length ? 'Some exercise illustrations were generated for ROOK using AI and reviewed for exercise identification.' : null;
const output = `// Generated by scripts/compile-visual-provenance.mjs. Do not edit.\n// The internal manifest/evidence is deliberately not imported by production.\nconst aiAssetIds = ${JSON.stringify(ai, null, 2)};\nconst otherAssets = ${JSON.stringify(other, null, 2)};\nexport const illustrationProvenance = Object.freeze({\n  ...Object.fromEntries(aiAssetIds.map(assetId => [assetId, Object.freeze({assetId, provenanceType: 'rook_ai_generated', attributionRequired: false, credit: null})])),\n  ...Object.fromEntries(Object.entries(otherAssets).map(([id, asset]) => [id, Object.freeze(asset)])),\n});\nexport const illustrationDisclosure = ${JSON.stringify(disclosure)};\nexport const requiredIllustrationCredits = Object.freeze(Object.values(illustrationProvenance).filter(asset => asset.attributionRequired).map(asset => Object.freeze({...asset.credit, assetId: asset.assetId})));\n`;
const target = path.join(root, 'src/illustrationProvenance.generated.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Public provenance is stale; run node scripts/compile-visual-provenance.mjs.');
  console.log(`Public provenance matches ${runtime.length} runtime records.`);
} else {
  fs.writeFileSync(target, output);
  console.log(`Compiled ${runtime.length} runtime records; ${runtime.filter(asset => asset.attributionRequired).length} required credit.`);
}
