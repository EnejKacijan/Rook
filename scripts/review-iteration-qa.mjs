import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createReturningUserFixture } from '../src/demoFixture.js';
import { exerciseName, isoDay, progressionFor, startWorkout, weekday } from '../src/domain.js';

const root = new URL('../artifacts/review-iteration/', import.meta.url);
await mkdir(root, { recursive: true });
const output = name => fileURLToPath(new URL(name, root));
const state = createReturningUserFixture(0);
const day = state.program.days.find(item => item.weekday === weekday()) || state.program.days[0];
const exercise = day.exercises[0];
const completedExercise = date => ({ ...structuredClone(exercise), sets: exercise.sets.map(set => ({ ...set, planned: true, added: false, completed: true, weight: 50, reps: exercise.repMax, rir: exercise.targetRir })) });
state.workouts = [7, 3].map((daysAgo, index) => ({ id: `review-session-${index}`, name: day.name, completedAt: new Date(Date.now() - daysAgo * 86400000).toISOString(), exercises: [completedExercise()] }));
state.selectedDay = day.weekday;
state.selectedDate = isoDay();
state.activeWorkout = startWorkout(state, day);
const recommendedWeight = progressionFor(state.activeWorkout.exercises[0], state.workouts, state.profile).weight;

const browser = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
await context.addInitScript(value => { if (!localStorage.getItem('lift-v2-state')) localStorage.setItem('lift-v2-state', JSON.stringify(value)); }, state);
const page = await context.newPage(); const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.route('**/api/ai/status', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ available: false }) }));
await page.goto('http://127.0.0.1:4173', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: 'RESUME WORKOUT' }).click();
await page.getByText('Ready to progress', { exact: true }).waitFor();
await page.getByText(/for today’s remaining sets/i).waitFor();
assert.equal(await page.locator('.up-next button').filter({ hasText: exerciseName(day.exercises[0]) }).count(), 0, 'Up Next excludes the current exercise');
const beforeUse = await page.evaluate(() => JSON.parse(localStorage.getItem('lift-v2-state')).activeWorkout.exercises[0].sets.map(set => set.weight));
assert.equal(beforeUse.every(weight => weight === 50), true, 'recommendation does not mutate weights before USE');
await page.screenshot({ path: output('390-progression-before-use.png'), fullPage: false });
await page.getByRole('button', { name: 'USE', exact: true }).click();
const afterUse = await page.evaluate(() => JSON.parse(localStorage.getItem('lift-v2-state')).activeWorkout.exercises[0].sets.map(set => set.weight));
assert.equal(afterUse.every(weight => weight === recommendedWeight), true, `USE applies the described weight to today’s remaining sets exactly once: ${JSON.stringify(afterUse)}`);
await page.getByRole('status').filter({ hasText: 'Applied to this workout' }).waitFor(); assert.equal(await page.getByRole('button', { name: 'USE', exact: true }).count(), 0, 'applied recommendation no longer presents a pending USE action');
await page.screenshot({ path: output('390-progression-after-use.png'), fullPage: false });
await page.reload({ waitUntil: 'networkidle' }); await page.getByRole('button', { name: 'RESUME WORKOUT' }).click(); assert.equal(await page.getByRole('button', { name: 'USE', exact: true }).count(), 0, 'reload preserves the applied state without re-applying it'); assert.equal(await page.evaluate(expected => JSON.parse(localStorage.getItem('lift-v2-state')).activeWorkout.exercises[0].sets.every(set => set.weight === expected), recommendedWeight), true);
assert.deepEqual(errors, []);
await context.close(); await browser.close();
console.log('Review iteration QA passed: recommendation is scoped to today and USE has deterministic before/after values.');
