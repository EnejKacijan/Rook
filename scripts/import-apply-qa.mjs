import { openProfileArea } from './qa-current-navigation.mjs';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createReturningUserFixture } from '../src/demoFixture.js';
import { STORAGE_KEY } from '../src/domain.js';
const directory=new URL('../artifacts/import-apply/',import.meta.url);await mkdir(directory,{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
try{
  const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'});
  const state=createReturningUserFixture(3);state.activeWorkout=null;
  await context.addInitScript(({state,key})=>{if(!localStorage.getItem(key))localStorage.setItem(key,JSON.stringify(state));},{state,key:STORAGE_KEY});
  const page=await context.newPage();const confirmations=[];
  page.on('dialog',async dialog=>{confirmations.push(dialog.message());await dialog.accept();});
  await page.goto('http://127.0.0.1:4173');
  const openPreview=async()=>{
  await page.getByRole('button',{name:'PROFILE',exact:true}).click();
  await openProfileArea(page, 'program'); await page.getByRole('button',{name:/Replace plan/}).click();
  await page.getByRole('button',{name:/Import from Notes|Import a different plan/}).click();
  await page.getByPlaceholder(/Paste your workout notes/).fill('Monday - Push\nBench Press 3x8 RIR 2\nCable Fly 2x12');
  await page.getByRole('button',{name:'CREATE PREVIEW',exact:true}).click();
  await page.getByRole('heading',{name:'Review your plan',exact:true}).waitFor();
  };
  await openPreview();
  const original=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),STORAGE_KEY);
  await page.reload();
  await page.getByRole('button',{name:'PROFILE',exact:true}).waitFor();
  assert.equal(await page.getByRole('heading',{name:'Review your plan',exact:true}).count(),0);
  assert.equal(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).program.id,STORAGE_KEY),original.program.id);
  await openPreview();
  await page.getByRole('button',{name:'USE THIS PLAN',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:fileURLToPath(new URL('01-final-preview.png',directory))});
  await page.evaluate(key=>{window.qaOriginalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k===key)throw new DOMException('QA quota','QuotaExceededError');return window.qaOriginalSetItem.call(this,k,v);};},STORAGE_KEY);
  await page.getByRole('button',{name:'USE THIS PLAN',exact:true}).click();
  await page.getByRole('alert').filter({hasText:/couldn’t save/}).waitFor();
  await page.waitForTimeout(200);
  const footerBottom=await page.locator('.sheet-action-footer').evaluate(node=>node.getBoundingClientRect().bottom);
  assert.ok(footerBottom>=820&&footerBottom<=864,`footer stays at the sheet bottom, got ${footerBottom}`);
  await page.screenshot({path:fileURLToPath(new URL('02-persistence-failure.png',directory))});
  assert.deepEqual(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),STORAGE_KEY),original);
  await page.evaluate(()=>{Storage.prototype.setItem=window.qaOriginalSetItem;delete window.qaOriginalSetItem;});
  await page.getByRole('button',{name:'USE THIS PLAN',exact:true}).click();
  await page.waitForFunction(key=>JSON.parse(localStorage.getItem(key))?.program?.source==='ai-import',STORAGE_KEY);
  const applied=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),STORAGE_KEY);
  assert.equal(applied.planVersions.length,original.planVersions.length+1);
  assert.deepEqual(applied.workouts,original.workouts);
  assert.equal(confirmations.length,2);
  assert.match(confirmations[0],/Replace the current program/);
  await page.getByRole('button',{name:'TODAY',exact:true}).click();
  await page.screenshot({path:fileURLToPath(new URL('03-applied.png',directory))});
  await page.reload();
  assert.equal(await page.evaluate(key=>JSON.parse(localStorage.getItem(key)).program.id,STORAGE_KEY),applied.program.id);
  console.log('Import apply: confirmation, failed write, retry, one version, history preservation, reload passed.');
}finally{await browser.close();}
