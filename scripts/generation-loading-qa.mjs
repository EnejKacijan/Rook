import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createReturningUserFixture } from '../src/demoFixture.js';

const outputRoot = new URL('../artifacts/generation-loading/', import.meta.url);
await mkdir(outputRoot, { recursive: true });
const output = name => fileURLToPath(new URL(name, outputRoot));
const browser = await chromium.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
await context.addInitScript(value => localStorage.setItem('lift-v2-state', JSON.stringify(value)), createReturningUserFixture(1));
const page = await context.newPage(); const errors = []; let aiPlanRequests = 0;
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.route('**/api/ai/status', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ available: true, provider: 'qa' }) }));
await page.route('**/api/ai', route => { aiPlanRequests += 1; return route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'Plan generation must stay local.' }) }); });
await page.goto('http://127.0.0.1:4173', { waitUntil: 'networkidle' });
await page.evaluate(() => {
  window.__generationStages = [];
  const record = () => { const title = document.querySelector('#building-title')?.textContent?.trim(); if (title && window.__generationStages.at(-1) !== title) window.__generationStages.push(title); };
  new MutationObserver(record).observe(document.body, { subtree: true, childList: true, characterData: true });
});
await page.getByRole('button', { name: 'PROFILE', exact: true }).click();
await page.getByRole('button', { name: 'REPLACE PLAN' }).click();
await page.getByRole('button', { name: /Build a personalized plan/ }).click();
await page.getByRole('button', { name: 'BUILD NEW PLAN' }).click();
await page.getByRole('heading', { name: 'Building your program…' }).waitFor();
await page.screenshot({ path: output('390-building.png'), fullPage: false });
await page.getByRole('heading', { name: 'Your week is ready.' }).waitFor();
const stages = await page.evaluate(() => window.__generationStages);
assert.ok(stages.includes('Building your program…'), 'local generation exposes a clear building state');
assert.ok(stages.includes('Checking your plan…'), 'local generation exposes deterministic validation');
assert.equal(aiPlanRequests, 0, 'building a normal plan never requires an AI request');
assert.equal(await page.locator('.building-overlay').count(), 0, 'loading overlay leaves when the preview is ready');
await page.screenshot({ path: output('390-local-preview.png'), fullPage: false });
await page.getByRole('button', { name: 'USE THIS PLAN' }).click();
await page.waitForFunction(() => JSON.parse(localStorage.getItem('lift-v2-state')).program.source === 'fixed-template');
const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('lift-v2-state')).program);
assert.ok(saved.templateId && saved.programmingVersion === 2, 'saved program retains its fixed-template identity');
assert.deepEqual(errors, [], `console remains clean: ${errors.join('; ')}`);
await context.close(); await browser.close();
console.log('Generation QA passed: local fixed-template build, visible validation, preview confirmation, and zero AI dependency.');
